// Error message mapping
const errorMessages: Record<string, string> = {
  'room_not_found': 'error_room_not_found',
  'invalid_password': 'error_invalid_password',
  'invalid_room_password': 'error_invalid_room_password',
  'username_taken': 'error_username_taken',
  'room_is_readonly': 'error_room_readonly',
  'room_name_taken': 'error_room_name_taken',
  'password_required': 'error_password_required',
  'internal_error': 'error_internal',
  'already_following': 'error_already_following',
  'no_active_session': 'error_already_following',
};

export function t(key: string, locale: Locale = 'zh-hans'): string {
  return translations[locale][key] || translations['zh-hans'][key] || key;
}

export function getErrorMessage(error: string | Error, locale: Locale = 'zh-hans'): string {
  const message = error instanceof Error ? error.message : error;
  
  // Try to match known error codes
  const errorKey = errorMessages[message];
  if (errorKey) {
    return t(errorKey, locale);
  }
  
  // If the key exists in translations, translate it
  if (translations[locale][message]) {
    return translations[locale][message];
  }
  
  // If it's already a translated-looking string (contains Chinese/Japanese), return as-is
  if (/[\u4e00-\u9fa5\u3040-\u309f\u30a0-\u30ff]/.test(message)) {
    return message;
  }
  
  // For unknown errors
  return t('error_unknown', locale);
}
